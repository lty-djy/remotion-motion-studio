import { build } from 'esbuild';
import assert from 'node:assert/strict';
const result = await build({entryPoints:['component-replacement.ts'], bundle:true, write:false, format:'esm', platform:'node'});
const {buildComponentReplacement, subtitleTextForInstance} = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const definition = (id, schema) => ({id, defaultProps:{}, propsSchema:schema});
const old = definition('old', {title:{type:'text',default:'示例'}, color:{type:'color',default:'#fff'}});
const next = definition('next', {headline:{type:'text',default:'默认标题'}, subtitle:{type:'text',default:'默认副标题'}, color:{type:'color',default:'#000'}});
const original = {id:'one', componentId:'old', startFrame:60, durationInFrames:90, sourceStartFrame:0, laneId:'lane', trackOrder:4, position:{x:24,y:42,scale:1.4}, arrangementBatchId:'batch', props:{title:'示例',color:'#f00'}};
const replacement = buildComponentReplacement(original,old,next,'真实字幕');
assert.equal(replacement.props.headline,'真实字幕');
assert.equal(replacement.props.subtitle,'');
assert.equal(replacement.props.color,'#f00');
for (const key of ['id','startFrame','durationInFrames','laneId','trackOrder','position','arrangementBatchId']) assert.deepEqual(replacement[key],original[key]);
assert.equal(original.props.title,'示例');
assert.equal(original.componentId,'old');
assert.equal(subtitleTextForInstance(replacement,[],30),'真实字幕');
const caption = {...original, componentId:'SrtSemanticCaptions',startFrame:30,sourceStartFrame:30, props:{cuesJson:JSON.stringify([{start:0,end:2,text:'不重叠'},{start:2,end:5,text:'对应字幕'},{start:5,end:7,text:'下一段'}])}};
assert.equal(subtitleTextForInstance(original,[caption],30),'对应字幕');
assert.equal(subtitleTextForInstance(original,[{...caption,arrangementBatchId:'other'}],30),'');
assert.equal(subtitleTextForInstance(original,[{...caption,props:{cuesJson:'broken'}}],30),'');
const edited = buildComponentReplacement({...original,props:{title:'人工改过'}},old,old,'字幕');
assert.equal(edited.props.title,'人工改过');
assert.equal(buildComponentReplacement(original,old,next,'').props.headline,'');
const metric = definition('metric', {conclusion:{type:'text',default:'示例结论'}, value:{type:'text',default:'100'}, unit:{type:'text',default:'元'}});
const numeric = buildComponentReplacement(original,old,metric,'效率提升了三倍');
assert.equal(numeric.props.value,'3');
assert.equal(numeric.props.unit,'倍');
assert.equal(numeric.props.conclusion,'效率提升了三倍');
assert.equal(buildComponentReplacement(original,old,metric,'一起来看').props.value,'');
assert.equal(buildComponentReplacement(original,old,metric,'20个工具只用3个').props.value,'');
console.log('PASS: content mapping, placeholder cleanup, manual edits, immutable draft, timing/lane preservation, caption overlap, batch isolation, malformed source and persisted provenance');
